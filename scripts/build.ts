// Build self-contained `enriched` binaries: the web surface is embedded, so each file is the whole product for its
// platform. No runtime to install and nothing that needs administrator rights.
//
//   bun scripts/build.ts            this machine only, linked as dist/bin/current/enriched
//   bun scripts/build.ts --all      macOS, Linux and Windows on x64 and arm64

import { createHash } from "node:crypto";
import { mkdirSync, readdirSync, readFileSync, rmSync, statSync, writeFileSync, copyFileSync } from "node:fs";
import { extname, join, relative } from "node:path";
import { $ } from "bun";

const root = join(import.meta.dir, "..");
const web = join(root, "packages", "web");
const out = join(root, "dist", "bin");
const generated = join(root, "packages", "engine", "src", "server", "ui_assets.gen.ts");

const MIME: Record<string, string> = {
	".html": "text/html; charset=utf-8",
	".js": "text/javascript; charset=utf-8",
	".css": "text/css; charset=utf-8",
	".svg": "image/svg+xml",
	".png": "image/png",
	".ico": "image/x-icon",
	".woff2": "font/woff2",
	".json": "application/json",
};

const TARGETS = ["darwin-arm64", "darwin-x64", "linux-x64", "linux-arm64", "windows-x64", "windows-arm64"];
const host = `${process.platform === "win32" ? "windows" : process.platform}-${process.arch}`;
const targets = process.argv.includes("--all") ? TARGETS : [host];

console.log("Building the web surface");
await $`bun run build`.cwd(web).quiet();

function walk(dir: string): string[] {
	return readdirSync(dir).flatMap((name) => {
		const path = join(dir, name);
		return statSync(path).isDirectory() ? walk(path) : [path];
	});
}
const dist = join(web, "dist");
const assets: Record<string, { type: string; data: string }> = {};
for (const file of walk(dist)) {
	assets[`/${relative(dist, file).split("\\").join("/")}`] = { type: MIME[extname(file)] ?? "application/octet-stream", data: readFileSync(file).toString("base64") };
}
writeFileSync(generated, `// Generated by scripts/build.ts. Do not edit.\nexport const assets: Record<string, { type: string; data: string }> = ${JSON.stringify(assets)};\n`);
console.log(`Embedded ${Object.keys(assets).length} web files`);
// The scripts apps import (/app-sdk/lab.js and app.js), bundled now so the binary needs nothing at run time.
const sdkGenerated = join(root, "packages", "engine", "src", "apps", "app_sdk.gen.ts");
const { buildSdk } = await import("../packages/engine/src/apps/sdk.ts");
writeFileSync(sdkGenerated, `// Generated by scripts/build.ts. Do not edit.\nexport const files: Record<string, string> = ${JSON.stringify(await buildSdk())};\n`);

mkdirSync(out, { recursive: true });
const sums: string[] = [];
try {
	for (const target of targets) {
		const exe = target.startsWith("windows") ? ".exe" : "";
		const file = join(out, `enriched-${target}${exe}`);
		await $`bun build ${join(root, "packages", "cli", "src", "main.ts")} --compile --minify --sourcemap=none --target=bun-${target} --outfile ${file}`.cwd(root).quiet();
		const digest = createHash("sha256").update(readFileSync(file)).digest("hex");
		sums.push(`${digest}  enriched-${target}${exe}`);
		console.log(`enriched-${target}${exe}  ${(statSync(file).size / 1_048_576).toFixed(0)} MB`);
	}
} finally {
	rmSync(generated, { force: true });
	rmSync(sdkGenerated, { force: true });
	// bun build --compile can leave its staging file (.<hash>.bun-build) in the working folder.
	for (const name of readdirSync(root)) if (name.endsWith(".bun-build")) rmSync(join(root, name), { force: true });
}
writeFileSync(join(out, "SHA256SUMS"), `${sums.join("\n")}\n`);
// What this release contains, for anyone checking it: a CycloneDX SBOM beside the binaries.
Bun.spawnSync(["bun", join(root, "scripts", "deps.ts"), "sbom"], { stdout: "inherit", stderr: "inherit" });

// Each platform's binary under a plain name, where the desktop build picks it up (apps/desktop: dist/stage/<os>-<arch>).
const OS: Record<string, string> = { darwin: "mac", linux: "linux", windows: "win" };
for (const target of targets) {
	const [os, arch] = target.split("-") as [string, string];
	const exe = os === "windows" ? ".exe" : "";
	const stage = join(root, "dist", "stage", `${OS[os]}-${arch}`);
	mkdirSync(stage, { recursive: true });
	rmSync(join(stage, `enriched${exe}`), { force: true });
	copyFileSync(join(out, `enriched-${target}${exe}`), join(stage, `enriched${exe}`));
}
